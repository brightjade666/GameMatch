package com.dong.springboot.vo;

public class UserInfoVO {
    private Integer user_id;
    private String username;
    private String nick;
    private String avatar;
    private Integer gender;
    private Integer age;
    private String contact;
    private String game_name;
    private String game_rank;
    private String personality;
    private String playtime;
    private String matchneed;
    private String introduction;
    private String create_time;
    private String update_time;

    public Integer getUser_id() { return user_id; }
    public void setUser_id(Integer user_id) { this.user_id = user_id; }
    public String getUsername() { return username; }
    public void setUsername(String username) { this.username = username; }
    public String getNick() { return nick; }
    public void setNick(String nick) { this.nick = nick; }
    public String getAvatar() { return avatar; }
    public void setAvatar(String avatar) { this.avatar = avatar; }
    public Integer getGender() { return gender; }
    public void setGender(Integer gender) { this.gender = gender; }
    public Integer getAge() { return age; }
    public void setAge(Integer age) { this.age = age; }
    public String getContact() { return contact; }
    public void setContact(String contact) { this.contact = contact; }
    public String getGame_name() { return game_name; }
    public void setGame_name(String game_name) { this.game_name = game_name; }
    public String getGame_rank() { return game_rank; }
    public void setGame_rank(String game_rank) { this.game_rank = game_rank; }
    public String getPersonality() { return personality; }
    public void setPersonality(String personality) { this.personality = personality; }
    public String getPlaytime() { return playtime; }
    public void setPlaytime(String playtime) { this.playtime = playtime; }
    public String getMatchneed() { return matchneed; }
    public void setMatchneed(String matchneed) { this.matchneed = matchneed; }
    public String getIntroduction() { return introduction; }
    public void setIntroduction(String introduction) { this.introduction = introduction; }
    public String getCreate_time() { return create_time; }
    public void setCreate_time(String create_time) { this.create_time = create_time; }
    public String getUpdate_time() { return update_time; }
    public void setUpdate_time(String update_time) { this.update_time = update_time; }
}